/** 가장 작은 원의 찬 몫을 말로 */
export function occWord(a) {
  if (a >= 99.5) return '가장 작은 원이 통째로 땅 안에 들어와요';
  if (a >= 85) return '가장 작은 원은 거의 다 땅이에요';
  if (a >= 65) return '가장 작은 원의 3분의 2쯤이 땅이에요';
  if (a >= 40) return '가장 작은 원은 절반 안팎만 땅이에요';
  if (a >= 20) return '가장 작은 원도 절반이 안 되게 땅이에요';
  return '가장 작은 원에서 땅이 겨우 조금 잡혀요';
}
/** 절반 반지름을 말로 */
export function halfWord(m) {
  if (m === 0) return '가장 작은 원에서 이미 절반 아래예요';
  if (m < 700) return '절반 선이 아주 가까워요';
  if (m < 2000) return '절반 선이 가까운 편이에요';
  if (m < 5000) return '절반 선이 중간쯤에 있어요';
  if (m < 10000) return '절반 선이 멀리 있어요';
  return '절반 선이 아주 멀어서 한참 키워야 꺼져요';
}
/** 빠지는 폭을 말로 */
export function dropWord(d) {
  if (d < 0) return '원을 키울수록 오히려 땅이 더 차요';
  if (d < 25) return '원을 키워도 거의 안 빠져요';
  if (d < 55) return '원을 키우면 절반 안쪽으로 빠져요';
  if (d < 75) return '원을 키우면 크게 빠져요';
  return '원을 키우면 대부분이 땅 밖으로 빠져요';
}
/** 두 값의 거리감 */
export const gapWord = (n) => (n < 5 ? '거의 같은' : n < 15 ? '가까운' : '꽤 벌어진');

